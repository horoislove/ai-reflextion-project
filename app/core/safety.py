"""Кризисный слой безопасности.

Срабатывает ДО обращения к LLM. Если в сообщении есть маркеры острого
кризиса (суицидальные мысли, намерение причинить себе вред), мы не отдаём
разговор языковой модели, а отвечаем заранее выверенным, бережным текстом
с контактами помощи.

Это не диагностика и не замена специалисту — задача минимальная и честная:
не навредить и направить к людям, которые могут помочь по-настоящему.
"""
import re

# Фразовые паттерны снижают ложные срабатывания по сравнению с отдельными
# словами ("убить время", "мёртвая тишина" не должны триггерить).
_CRISIS_PATTERNS = [
    r"не хочу (больше )?жить",
    r"не хочется жить",
    r"хочу (умереть|сдохнть|сдохнуть|исчезнуть|чтобы всё закончилось)",
    r"покончить с собой",
    r"покончить с жизнью",
    r"свести счёты с жизнью",
    r"свести счеты с жизнью",
    r"убить себя",
    r"убью себя",
    r"\bсуицид",
    r"самоуб[иь]йств",
    r"наложить на себя руки",
    r"причинить себе (вред|боль)",
    r"режу себя",
    r"режу руки",
    r"selfharm|self-harm",
    r"kill myself",
    r"want to die",
    r"end my life",
    r"suicide",
    r"лучше бы меня не было",
    r"всем будет лучше без меня",
    r"не вижу смысла жить",
    r"смысла жить нет",
]

_CRISIS_RE = re.compile("|".join(_CRISIS_PATTERNS), re.IGNORECASE)

CRISIS_RESPONSE = (
    "Я слышу, что тебе сейчас очень тяжело, и я рядом. "
    "Спасибо, что говоришь об этом вслух — это важно.\n\n"
    "Я — поддерживающий собеседник, и мне важно быть честным: с такой болью "
    "не стоит оставаться один на один, и я не могу заменить живого человека, "
    "который умеет помогать в острые моменты. Пожалуйста, дай себе эту "
    "поддержку прямо сейчас:\n\n"
    "• Телефон доверия (бесплатно, круглосуточно): 8-800-2000-122\n"
    "• Экстренные службы: 112\n"
    "• Если есть кто-то близкий рядом — побудь рядом с ним.\n\n"
    "Я никуда не уйду. Если хочешь, расскажи, что наваливается на тебя "
    "прямо сейчас — мы можем побыть с этим вместе."
)


def is_crisis(text: str) -> bool:
    """Есть ли в сообщении маркеры острого кризиса."""
    if not text:
        return False
    return _CRISIS_RE.search(text) is not None